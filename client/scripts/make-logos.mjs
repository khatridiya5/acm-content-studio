// Turns the two logos into small embedded images so they survive PNG/PDF export.
import sharp from 'sharp';
import { writeFileSync, mkdirSync } from 'node:fs';

async function uri(path) {
  const buf = await sharp(path).resize(300, 300, { fit: 'inside' }).png({ compressionLevel: 9, palette: true }).toBuffer();
  return 'data:image/png;base64,' + buf.toString('base64');
}
const acm = await uri('public/brand/acm_logo.png');
const svnit = await uri('public/brand/svnit_logo.jpg');
mkdirSync('src/core/brand', { recursive: true });
writeFileSync('src/core/brand/logos.ts',
  `// AUTO-GENERATED by scripts/make-logos.mjs. Do not edit.\nexport const LOGO_ACM = '${acm}';\nexport const LOGO_SVNIT = '${svnit}';\n`);
console.log('Logos written to src/core/brand/logos.ts');